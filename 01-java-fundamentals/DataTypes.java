public class DataTypes {
    public static void main(String[] args) {

        byte smallNumber = 100;
        short shortNumber = 20000;
        int number = 50000;
        long largeNumber = 9876543210L;

        float decimalNumber = 10.5f;
        double preciseNumber = 99.99;

        char grade = 'A';
        boolean isJavaFun = true;

        System.out.println("Byte: " + smallNumber);
        System.out.println("Short: " + shortNumber);
        System.out.println("Integer: " + number);
        System.out.println("Long: " + largeNumber);
        System.out.println("Float: " + decimalNumber);
        System.out.println("Double: " + preciseNumber);
        System.out.println("Character: " + grade);
        System.out.println("Boolean: " + isJavaFun);
    }
}